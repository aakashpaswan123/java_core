public class BooleanExample{
	public static void main(String[]args){
		//boolean Java का सबसे सरल primitive data type है। इसमें केवल 2 values हो सकती हैं:
		//true
		//false
		//Size: JVM पर निर्भर करता है (Java Language Specification कोई fixed byte size नहीं बताती)
       //Default value (instance variable): false
	   
	   boolean isjavaEasy = true;
	   System.out.println(isjavaEasy); //true
	   
	   //comparison
	   boolean result = (10>5);
	   System.out.println(result); //true
	   
	}
}